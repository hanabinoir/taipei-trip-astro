export type LanguageKey = "zh-TW" | "ja";
export type TranslationKey = keyof typeof translations.transportation;

export const getLanguage = (): LanguageKey => {
  if (typeof window === "undefined") return "zh-TW";
  const saved = localStorage.getItem("trip-language");
  return saved === "ja" ? "ja" : "zh-TW";
};

export const getTranslation = (section: string, key: string, language?: LanguageKey): string => {
  const lang = language || getLanguage();
  const sectionPath = section.split(".").reduce((obj: any, part) => obj?.[part], translations.transportation);
  const value = sectionPath?.[key];
  
  if (!value) {
    console.warn(`Translation not found: ${section}.${key}`);
    return key;
  }
  
  return value[lang] || value["zh-TW"] || key;
};
